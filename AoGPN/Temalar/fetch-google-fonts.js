#!/usr/bin/env node
/**
 * fetch-google-fonts.js — regenerates the BUNDLED dashboard fonts.
 *
 * Downloads every font the dashboard and skins use (Inter, Orbitron,
 * Rajdhani, VT323) from the Google Fonts css2 API as woff2 files plus a
 * generated `fonts.css`, all under Temalar/fonts/. The output is COMMITTED,
 * so builds and offline installs get the exact same typography with zero
 * network access at runtime (and no render-blocking fetch at boot).
 *
 * Usage:  node Temalar/fetch-google-fonts.js   (from the AoGPN solution dir)
 *
 * The generated fonts.css keeps the served @font-face declarations verbatim
 * (family/style/weight/font-display/unicode-range) and only rewrites the src
 * URLs to the local files, so the on-screen look is identical to the remote
 * stylesheet. File names are {family}-{weight}-{n}.woff2 in the deterministic
 * order Google serves the subset blocks; regeneration replaces them in place.
 */

'use strict';

const https = require('https');
const fs = require('fs');
const path = require('path');

const FONTS_DIR = path.join(__dirname, 'fonts');
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
  '(KHTML, like Gecko) Chrome/126.0 Safari/537.36';

// Exactly what the dashboard and skins request today:
//   vpn-gpn-dashboard.html + NEXUS: Inter 400;500;600, Orbitron 500;600;700, Rajdhani 500;600;700
//   CYBER skin: Rajdhani 500;600;700;900, VT323
const FAMILIES = [
  'family=Inter:wght@400;500;600',
  'family=Orbitron:wght@500;600;700',
  'family=Rajdhani:wght@500;600;700;900',
  'family=VT323',
];

function slug(family) {
  return family.toLowerCase().replace(/[^a-z0-9]+/g, '-');
}

function get(url, binary) {
  return new Promise((resolve, reject) => {
    https
      .get(url, { headers: { 'User-Agent': UA } }, (res) => {
        if (res.statusCode !== 200) {
          res.resume();
          reject(new Error(`HTTP ${res.statusCode} for ${url}`));
          return;
        }
        const chunks = [];
        res.on('data', (c) => chunks.push(c));
        res.on('end', () =>
          resolve(binary ? Buffer.concat(chunks) : Buffer.concat(chunks).toString('utf8'))
        );
      })
      .on('error', reject);
  });
}

async function main() {
  fs.mkdirSync(FONTS_DIR, { recursive: true });

  const blocks = [];
  for (const fam of FAMILIES) {
    const css = await get(`https://fonts.googleapis.com/css2?${fam}&display=swap`, false);
    const found = [...css.matchAll(/@font-face\s*{([^}]*)}/g)].map((m) => m[1]);
    if (found.length === 0) {
      throw new Error(`No @font-face blocks for ${fam}`);
    }
    blocks.push(...found.map((body) => ({ body, familyParam: fam })));
  }

  const faceCount = new Map();
  // Deduplicate: Google serves variable fonts as ONE file shared by several
  // weights (e.g. Orbitron) — identical bytes must not be stored three times.
  const hashToFile = new Map();
  const outBlocks = [];
  let totalBytes = 0;

  for (const { body } of blocks) {
    const prop = (name) => {
      const m = body.match(new RegExp(name + '\\s*:\\s*([^;]+);'));
      return m ? m[1].trim() : null;
    };

    const family = (prop('font-family') || '').replace(/['"]/g, '').trim();
    const style = prop('font-style') || 'normal';
    const weight = prop('font-weight') || '400';
    const display = prop('font-display') || 'swap';
    const unicodeRange = prop('unicode-range') || '';
    const srcMatch = body.match(/url\(([^)]+)\)\s*format\((['"]?)woff2\2\)/);
    if (!family || !srcMatch) {
      continue;
    }

    const key = `${slug(family)}-${weight}`;
    const n = (faceCount.get(key) || 0) + 1;
    faceCount.set(key, n);
    const fileName = `${key}-${n}.woff2`;
    const filePath = path.join(FONTS_DIR, fileName);

    const buf = await get(srcMatch[1].replace(/^['"]|['"]$/g, ''), true);
    const crypto = require('crypto');
    const hash = crypto.createHash('sha256').update(buf).digest('hex').slice(0, 16);
    const existing = hashToFile.get(hash);
    const usedName = existing ?? fileName;
    if (!existing) {
      hashToFile.set(hash, fileName);
      fs.writeFileSync(filePath, buf);
    }
    totalBytes += buf.length;

    outBlocks.push(
      `/* ${family} ${weight} (${style}) — subset block ${n} */\n` +
        `@font-face {\n` +
        `  font-family: '${family}';\n` +
        `  font-style: ${style};\n` +
        `  font-weight: ${weight};\n` +
        `  font-display: ${display};\n` +
        `  src: url('./${usedName}') format('woff2');\n` +
        (unicodeRange ? `  unicode-range: ${unicodeRange};\n` : '') +
        `}\n`
    );
  }

  const header =
    `/* ==========================================================================\n` +
    `   Bundled dashboard fonts — generated by Temalar/fetch-google-fonts.js\n` +
    `   (node Temalar/fetch-google-fonts.js). DO NOT EDIT BY HAND.\n` +
    `   Served locally so the dashboard and skins render identically offline\n` +
    `   (no network fetch, no render-blocking stylesheet at boot).\n` +
    `   ========================================================================== */\n\n`;

  fs.writeFileSync(path.join(FONTS_DIR, 'fonts.css'), header + outBlocks.join('\n'));
  console.log(
    `OK: ${outBlocks.length} @font-face blocks, ${faceCount.size} family-weight files, ` +
      `${(totalBytes / 1024).toFixed(0)} KB total -> ${FONTS_DIR}`
  );
}

main().catch((err) => {
  console.error('fetch-google-fonts failed:', err.message);
  process.exit(1);
});